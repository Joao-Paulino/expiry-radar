func TestCheck_ManagedCertificates(t *testing.T) {
	f := managedCertsFake(t)
	recs, err := newTestChecker(t, f, Config{Subscriptions: []string{guid}, ManagedCertificates: true}).Check(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]map[string]string{}
	exp := map[string]time.Time{}
	for _, r := range recs {
		if err := r.Validate(); err != nil {
			t.Fatalf("invalid record %+v: %v", r, err)
		}
		if r.Kind != "certificate" || !strings.HasPrefix(r.Source, "azure://arm/subscriptions/") {
			t.Fatalf("record %+v", r)
		}
		got[r.Metadata["service"]+"|"+r.Name] = r.Metadata
		exp[r.Metadata["service"]+"|"+r.Name] = r.ExpiresAt
	}
	want := []string{
		"app_service|api.contoso.com",
		"app_service_certificate_order|*.contoso.com",
		"front_door|*.contoso.com",
		"front_door|bar.contoso.com",
		"application_gateway|agw-prod/www-cert",
	}
	for _, w := range want {
		if got[w] == nil {
			t.Errorf("missing %s in %v", w, got)
		}
	}
	if len(got) != len(want) {
		t.Fatalf("want %d records (expired leftover, classic CDN, URL signing key and KV-only cert skipped), got %v", len(want), got)
	}
	if !exp["application_gateway|agw-prod/www-cert"].Equal(time.Date(2036, 11, 9, 0, 1, 26, 0, time.UTC)) {
		t.Fatalf("App Gateway leaf expiry %v (CA certificate picked?)", exp["application_gateway|agw-prod/www-cert"])
	}
	if !exp["front_door|bar.contoso.com"].Equal(time.Date(2027, 1, 1, 0, 0, 0, 0, time.UTC)) {
		t.Fatalf("'-00:00' offset not parsed: %v", exp["front_door|bar.contoso.com"])
	}
	if m := got["app_service_certificate_order|*.contoso.com"]; m["auto_renew"] != "false" || m["resource_group"] != "rg-web" || m["subscription"] != guid {
		t.Fatalf("order metadata %v", m)
	}
	if m := got["front_door|bar.contoso.com"]; m["certificate_type"] != "ManagedCertificate" || m["profile"] != "profile1" {
		t.Fatalf("front door metadata %v", m)
	}
	if m := got["application_gateway|agw-prod/www-cert"]; m["common_name"] != "www.contoso.com" {
		t.Fatalf("app gateway metadata %v", m)
	}
}

func TestCheck_ManagedCertificatesPartialFailure(t *testing.T) {
	f := managedCertsFake(t)
	f.armFail = "/subscriptions/" + guid + "/providers/Microsoft.Network/applicationGateways"
	recs, err := newTestChecker(t, f, Config{Subscriptions: []string{guid}, ManagedCertificates: true}).Check(context.Background())
	if err == nil || !strings.Contains(err.Error(), "applicationGateways") || len(recs) != 4 {
		t.Fatalf("want 4 records and the App Gateway error, got %d, %v", len(recs), err)
	}
}

func TestParsePublicCertData(t *testing.T) {
	b64, _ := os.ReadFile("testdata/appgw-publicCertData.b64")
	cert, err := leafFromPublicCertData(strings.TrimSpace(string(b64)))
	if err != nil || cert.Subject.CommonName != "www.contoso.com" {
		t.Fatalf("got %v, %v", cert, err)
	}
	for _, bad := range []string{"", "!!!", "aGVsbG8="} {
		if _, err := leafFromPublicCertData(bad); err == nil {
			t.Errorf("%q accepted", bad)
		}
	}
}
